#!/usr/bin/env bash
# Generate, from tests/examples/, the envelope request bodies and a matching hurl file so
# hurl can drive every example from disk (hurl can't wrap raw source into the JSON
# envelope itself). Outputs:
#   tests/bodies/<name>.json   one envelope per example (e.g. 1.py.json, 7.ts.json)
#   tests/examples.hurl        one POST per example, body read via file,...;
# Both are generated artifacts (git-ignored); tests/examples/ stays the single source.
#
#   tests/gen-bodies.sh
#   spin up --listen 127.0.0.1:3007 &
#   hurl --variable base_url=http://127.0.0.1:3007 --test tests/examples.hurl
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
EXAMPLES="$HERE/examples"
BODIES="$HERE/bodies"
HURL="$HERE/examples.hurl"
source "$HERE/lib.sh"

mkdir -p "$BODIES"
rm -f "$BODIES"/*.py.json "$BODIES"/*.ts.json   # clear stale generated bodies (keep hand-written fixtures)

{
  echo "# GENERATED by tests/gen-bodies.sh; do not edit."
  echo "# Drives every tests/examples/* file from disk; bodies are in tests/bodies/<name>.json."
  echo "# Run: hurl --variable base_url=http://127.0.0.1:3007 --test tests/examples.hurl"
} > "$HURL"

count=0
while IFS= read -r -u 3 f; do
  src="$EXAMPLES/$f"
  [ -f "$src" ] || continue
  lang="$(detect_lang "$src")"
  input="$(input_for "$f")"
    kv_enabled="$(kv_enabled_for "$f")"

  # envelope body (sandboxId derived from the code so reruns are stable)
    jq -n --rawfile c "$src" --argjson in "$input" --argjson kv "$kv_enabled" \
      '{code:$c, sandboxId:("ex-"+($c|@base64|.[0:8])), input:$in, kvEnabled:$kv}' > "$BODIES/$f.json"
  count=$((count + 1))

  if is_known_fail "$f"; then
    printf '\n# %s (%s), KNOWN-FAIL (pinned); body at bodies/%s.json, not asserted\n' \
      "$f" "$lang" "$f" >> "$HURL"
    continue
  fi

  {
    printf '\n# %s (%s)\n' "$f" "$lang"
    echo "POST {{base_url}}/$lang/run"
    echo "content-type: application/json"
    echo "file,bodies/$f.json;"
    echo "HTTP *"
    echo "[Asserts]"
    echo "status >= 200"
    echo "status < 400"
    # main-program scripts return {stdout,stderr,error}; assert the run didn't raise.
    is_main_shape "$src" && echo 'jsonpath "$.error" == null'
  } >> "$HURL"
done 3< <(list_examples "$EXAMPLES")

echo "generated $count bodies in $BODIES and $HURL"
